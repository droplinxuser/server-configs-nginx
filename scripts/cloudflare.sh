#!/usr/bin/env bash
# Refresh the Cloudflare real-IP trust list for Angie/Nginx.
#
# The file is written atomically and only replaced after the downloaded ranges
# validate, so a Cloudflare outage or an HTML error page can never leave a
# half-written include behind.
set -Eeuo pipefail
umask 022

readonly CLOUDFLARE_FILE_PATH=/etc/angie/http.d/cloudflare.conf
TMP_FILE=$(mktemp "${CLOUDFLARE_FILE_PATH}.XXXXXX")
readonly TMP_FILE
trap 'rm -f "$TMP_FILE"' EXIT

fetch_ranges() {
  local url=$1 body
  body=$(curl -fsSL --proto '=https' --tlsv1.2 \
    --connect-timeout 10 --max-time 30 --retry 3 --retry-delay 2 "$url")
  [[ -n $body ]] || return 1
  printf '%s\n' "$body" | awk '
    /^[0-9a-fA-F:.]+\/[0-9]{1,3}$/ {
      print "set_real_ip_from " $0 ";"
      count++
    }
    END { exit (count > 0 ? 0 : 1) }
  '
}

{
  echo "# Generated by scripts/cloudflare.sh - do not edit by hand."
  echo "# Include this file in your vhost."
  echo
  fetch_ranges https://www.cloudflare.com/ips-v4
  fetch_ranges https://www.cloudflare.com/ips-v6
  echo
  echo "real_ip_header CF-Connecting-IP;"
} > "$TMP_FILE"

install -m 644 "$TMP_FILE" "$CLOUDFLARE_FILE_PATH"

# Test before reloading; keep a valid old file if the generated one is bad.
if /usr/sbin/angie -t; then
  /usr/bin/systemctl reload angie.service
else
  echo "ERROR: Angie rejected the refreshed Cloudflare list" >&2
  exit 1
fi
